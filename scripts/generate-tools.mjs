// Writes src/tools/modules.generated.ts: one static import per tool file in src/tools/.
// Runs before tsc (npm "prebuild"), so adding a tool is just adding its file.
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/tools/', import.meta.url);
const NOT_TOOLS = new Set(['index.ts', 'context.ts', 'modules.generated.ts']);

const files = readdirSync(dir, { withFileTypes: true })
  .filter((e) => e.isFile() && e.name.endsWith('.ts') && !NOT_TOOLS.has(e.name))
  .map((e) => e.name.slice(0, -3))
  .sort();

const bad = files.filter((f) => !/^[a-z]+(-[a-z]+)*$/.test(f));
if (bad.length) {
  console.error(`Tool files must be kebab-case, named after their tool (e.g. list-ghost-tags.ts): ${bad.join(', ')}`);
  process.exit(1);
}

const camel = (n) => n.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const out = [
  '// Generated by scripts/generate-tools.mjs. Do not edit or commit.',
  "import type { ToolModule } from './context.js';",
  ...files.map((f) => `import ${camel(f)} from './${f}.js';`),
  '',
  'export const modules: ToolModule[] = [',
  ...files.map((f) => `  ${camel(f)},`),
  '];',
  '',
].join('\n');

writeFileSync(new URL('modules.generated.ts', dir), out);
console.log(`generated ${files.length} tool modules`);
